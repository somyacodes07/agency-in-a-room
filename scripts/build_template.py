#!/usr/bin/env python3
"""Builds agency-in-a-room.template.yaml from agents/*.md and rate-card.md.

Edit the Markdown files, then run:  python3 scripts/build_template.py
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent

# name, description, addressing
TEAM = [
    ("intake", "Scopes the client request: in scope, out of scope, constraints, up to 2 questions.", "owner-agents"),
    ("estimator", "Prices the scope from the room's rate card and finds a Phase 1 that fits the budget.", "owner-agents"),
    ("proposal", "Writes deliverables, timeline, price and terms; revises once from the advocate's risks.", "owner-agents"),
    ("advocate", "Devil's Advocate: flags risks with evidence and fixes, then hands the decision to the human.", "owner-agents"),
    # owner only: Switch itself guarantees no agent can trigger the close.
    ("closer", "Acts only on the human's APPROVE or REJECT: client email, kickoff checklist, signed-off doc.", "owner"),
]


def block(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join((pad + line) if line else "" for line in text.strip().splitlines())


def quoted(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


agents = []
for name, desc, addressing in TEAM:
    instr = (root / "agents" / f"{name}.md").read_text()
    agents.append(f"""  - name: "{{team}}-{name}"
    display_name: "{{team}}-{name}"
    description: {quoted(desc)}
    provider: "{{provider}}"
    location: "{{location}}"
    directory: "{{$agents_dir}}/{{team}}-{name}"
    addressing: {addressing}
    allow_existing: true
    instructions: |
{block(instr, 6)}""")

rate_card = (root / "rate-card.md").read_text()
request = (
    "Full website with online ordering, payments, delivery tracking and a mobile app, "
    "live in 3 days, $200 budget, free changes after launch."
)

doc = f"""# Agency in a Room: a Switch template.
# A client request enters a chat room and five agents run it like a small agency:
#   intake -> estimator -> proposal -> advocate -> (you: APPROVE / REJECT) -> closer
# Generated by scripts/build_template.py from agents/*.md and rate-card.md.
# Edit those files, then rebuild. Do not edit this file by hand.
version: 1
params:
  team:
    type: string
    label: Team name
    description: Prefix for the five agents (team-intake, team-estimator, ...). Use a new name to run a second team.
    default: agency
    pattern: "[a-z][a-z0-9]+"
  request:
    type: string
    label: Client request
    multiline: true
    default: {quoted(request)}
  client_name:
    type: string
    label: Client name
    description: Used in the closer's email greeting.
    default: there
    input: advanced
  agency_name:
    type: string
    label: Your agency name
    description: Used to sign the closer's email.
    default: Agency in a Room Studio
    input: advanced
  rate_card:
    type: string
    label: Your rate card
    description: The estimator prices only from this. Replace it with your own rates.
    multiline: true
    input: advanced
    default: |
{block(rate_card, 6)}
  bridge:
    type: bridge
    label: Messaging app
    description: Where the room is created. Telegram bots can't create chats, so for Telegram see docs/telegram in the repo.
    default: [Mattermost, $first]
    input: advanced
  provider:
    type: provider
    default: [antigravity, claude, codex, opencode, $first]
    input: advanced
  location:
    type: location
    default: local
    input: advanced
agents:
{chr(10).join(agents)}
room:
  name: "{{team}} client desk"
  description: Client request in, priced and risk-checked proposal out, human sign-off before anything is final.
  bridge: "{{bridge}}"
  agents: ["{{team}}-intake", "{{team}}-estimator", "{{team}}-proposal", "{{team}}-advocate", "{{team}}-closer"]
  users: ["{{$creator}}"]
  instructions: |
    This room runs one client request through a small agency pipeline:
    {{team}}-intake scopes it, {{team}}-estimator prices it from the rate card,
    {{team}}-proposal drafts the offer, {{team}}-advocate reviews the risks,
    {{team}}-proposal revises once, and the human owner decides. Only the owner can
    wake {{team}}-closer, by replying "@{{team}}-closer APPROVE" or "@{{team}}-closer REJECT".
    Agents hand off by @-mentioning the next agent. Nothing is final until the owner approves.

    Rate card (the only source of prices):
    {{rate_card}}
  docs:
    - name: Rate card
      description: The agency's prices. The estimator uses only these.
      instructions: Read-only reference for pricing.
      content: "{{rate_card}}"
kickoff: |
  @{{team}}-intake New client request:

  {{request}}
"""
(root / "agency-in-a-room.template.yaml").write_text(doc)
print("wrote agency-in-a-room.template.yaml")

# Telegram rooms are adopted from an existing group, not created by the template,
# so write the room instructions out ready to paste (team "agency", default rate card).
start = doc.index("  instructions: |\n    This room runs")
end = doc.index("  docs:", start)
room_instr = "\n".join(line[4:] for line in doc[start:end].splitlines()[1:])
room_instr = room_instr.replace("{rate_card}", rate_card.strip()).replace("{team}", "agency")
(root / "docs" / "telegram").mkdir(parents=True, exist_ok=True)
(root / "docs" / "telegram" / "room-instructions.txt").write_text(room_instr.strip() + "\n")
print("wrote docs/telegram/room-instructions.txt")
